"""## **2. Pra-pemrosesan Data (Preprocessing)**

Sebelum data dapat digunakan untuk melatih model, diperlukan beberapa langkah pra-pemrosesan. Tahapan ini sangat penting untuk membersihkan data teks dari *noise* dan mengubahnya menjadi format numerik yang dapat dipahami oleh model.

Langkah-langkah yang dilakukan meliputi:
1.  **Pembersihan Teks**: Menghapus elemen yang tidak relevan seperti tag HTML (`<br>`) dan karakter khusus (tanda baca) dari setiap ulasan. Teks juga diubah menjadi huruf kecil (*lowercase*) untuk konsistensi.
2.  **Tokenisasi**: Memecah setiap ulasan menjadi daftar kata-kata individual (token).
3.  **Pembuatan Kosakata (Vocabulary)**: Membuat kamus dari semua token unik yang ada di seluruh dataset. Setiap token diberi indeks numerik yang unik. Token khusus seperti `<PAD>` (untuk *padding*) dan `<UNK>` (*unknown*, untuk kata-kata yang tidak ada di kosakata) juga ditambahkan.
4.  **Encoding & Padding**: Mengubah setiap ulasan (yang sudah berupa daftar token) menjadi urutan indeks numerik berdasarkan kosakata yang telah dibuat. Setiap urutan kemudian dipotong atau ditambahkan *padding* (dengan nilai 0) agar memiliki panjang yang seragam (`MAX_LEN = 100`). Ini diperlukan agar semua input ke model memiliki dimensi yang sama.
"""

def clean_text(text):
    text = re.sub(r'<.*?>', ' ', text)  # Remove HTML tags
    text = re.sub(r'[^a-zA-Z0-9\s]', '', text)  # Remove special chars
    return text.lower()

df["text"] = df["review"].apply(clean_text)
df

def tokenize(text):
    return text.split()

df["tokens"] = df["text"].apply(tokenize)

all_tokens = [token for tokens in df["tokens"] for token in tokens]
vocab = {token: i+2 for i, (token, _) in enumerate(Counter(all_tokens).items())}
vocab["<PAD>"] = 0
vocab["<UNK>"] = 1

def encode(tokens):
    return [vocab.get(token, 1) for token in tokens]

df["input_ids"] = df["tokens"].apply(encode)

MAX_LEN = 100

def pad_input(input_ids):
    return input_ids[:MAX_LEN] + [0]*(MAX_LEN - len(input_ids))

df["padded"] = df["input_ids"].apply(pad_input)

class ReviewDataset(Dataset):
    def __init__(self, df):
        self.inputs = torch.tensor(df["padded"].tolist(), dtype=torch.long)
        self.labels = torch.tensor(df["label"].tolist(), dtype=torch.float32)

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        return self.inputs[idx], self.labels[idx]

dataset = ReviewDataset(df)
train_size = int(0.8 * len(dataset))
train_ds, val_ds = random_split(dataset, [train_size, len(dataset) - train_size])
train_loader = DataLoader(train_ds, batch_size=32, shuffle=True)
val_loader = DataLoader(val_ds, batch_size=32)

"""## **3. Arsitektur Model**

Dalam proyek ini, kita akan membandingkan tiga arsitektur yang berbeda. Semua model akan memiliki lapisan *embedding* yang sama, yang berfungsi untuk mengubah indeks numerik dari setiap kata menjadi vektor padat (*dense vector*). Vektor ini menangkap makna semantik dari kata.

Berikut adalah arsitektur yang dievaluasi:

**BASE MODEL CLASS**
"""

class BaseModel(nn.Module):
    def __init__(self, vocab_size, embed_dim):
        super().__init__()
        self.embedding = nn.Embedding(vocab_size, embed_dim)
        self.fc = nn.Linear(embed_dim, 1)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        raise NotImplementedError

"""### **3.1. Recurrent Neural Network (RNN)**

RNN adalah jenis jaringan saraf yang dirancang untuk memproses data sekuensial. Arsitektur ini memiliki "memori" yang memungkinkannya untuk menggunakan informasi dari input sebelumnya dalam memproses input saat ini. Namun, RNN dasar memiliki kelemahan yang dikenal sebagai *vanishing gradient problem*, yang membuatnya sulit untuk mempelajari dependensi jangka panjang dalam urutan yang panjang.

**RNN**
"""

class RNNModel(BaseModel):
    def __init__(self, vocab_size, embed_dim, hidden_dim=64):
        super().__init__(vocab_size, embed_dim)
        self.rnn = nn.RNN(embed_dim, hidden_dim, batch_first=True)
        self.fc = nn.Linear(hidden_dim, 1)

    def forward(self, x):
        x = self.embedding(x)
        _, h_n = self.rnn(x)
        out = self.fc(h_n.squeeze(0))
        return self.sigmoid(out)

"""### **3.2. Long Short-Term Memory (LSTM)**

LSTM adalah varian dari RNN yang dirancang khusus untuk mengatasi masalah *vanishing gradient*. LSTM memiliki struktur sel yang lebih kompleks dengan tiga "gerbang" (*gates*): *input gate*, *forget gate*, dan *output gate*. Gerbang-gerbang ini mengatur aliran informasi, memungkinkan model untuk menyimpan atau membuang informasi dari memori selnya. Kemampuan ini membuat LSTM lebih efektif dalam menangkap dependensi jangka panjang dibandingkan RNN dasar.

**LSTM**
"""

class LSTMModel(BaseModel):
    def __init__(self, vocab_size, embed_dim, hidden_dim=64):
        super().__init__(vocab_size, embed_dim)
        self.lstm = nn.LSTM(embed_dim, hidden_dim, batch_first=True)
        self.fc = nn.Linear(hidden_dim, 1)

    def forward(self, x):
        x = self.embedding(x)
        _, (h_n, _) = self.lstm(x)
        out = self.fc(h_n.squeeze(0))
        return self.sigmoid(out)

"""### **3.3. Transformer**

Transformer adalah arsitektur yang lebih modern yang tidak bergantung pada struktur sekuensial seperti RNN atau LSTM. Sebaliknya, ia menggunakan mekanisme yang disebut **atensi** (*attention*), khususnya *self-attention*. Mekanisme ini memungkinkan model untuk menimbang pentingnya setiap kata dalam urutan input saat memproses kata lain. Dengan demikian, Transformer dapat menangkap hubungan antara kata-kata yang berjauhan secara lebih efisien dan dapat diparalelkan proses pelatihannya, membuatnya jauh lebih cepat daripada RNN/LSTM pada dataset besar. Model yang kita implementasikan di sini adalah *Transformer Encoder*.

**Transformer**
"""

class TransformerModel(BaseModel):
    def __init__(self, vocab_size, embed_dim, num_heads=2, num_layers=2):
        super().__init__(vocab_size, embed_dim)
        encoder_layer = nn.TransformerEncoderLayer(d_model=embed_dim, nhead=num_heads)
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.fc = nn.Linear(embed_dim, 1)

    def forward(self, x):
        x = self.embedding(x).permute(1, 0, 2)  # [seq_len, batch, embed]
        out = self.transformer(x)
        out = out[0]  # ambil output dari token pertama
        return self.sigmoid(self.fc(out))

"""## **4. Pelatihan dan Evaluasi**

Setiap model dilatih selama **5 epoch** dengan *learning rate* **0.001**. Fungsi kerugian (*loss function*) yang digunakan adalah **Binary Cross-Entropy Loss (BCELoss)**, yang cocok untuk masalah klasifikasi biner. *Optimizer* yang dipilih adalah **Adam**, yang merupakan algoritma optimisasi yang populer dan efektif.

Data dibagi menjadi 80% untuk pelatihan (*training*) dan 20% untuk validasi (*validation*). Akurasi pada set validasi dihitung setelah setiap epoch untuk memantau kinerja model pada data yang belum pernah dilihat sebelumnya.

**Training & Evaluation**
"""

def train(model, train_loader, val_loader, epochs=5, lr=0.001):
    model = model.to(device)
    criterion = nn.BCELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    accuracies = []

    for epoch in range(epochs):
        model.train()
        for inputs, labels in train_loader:
            inputs, labels = inputs.to(device), labels.to(device).unsqueeze(1)
            outputs = model(inputs)
            loss = criterion(outputs, labels)
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

        model.eval()
        preds, truths = [], []
        with torch.no_grad():
            for inputs, labels in val_loader:
                inputs = inputs.to(device)
                outputs = model(inputs)
                preds.extend((outputs.cpu().numpy() > 0.5).astype(int))
                truths.extend(labels.numpy())

        acc = accuracy_score(truths, preds)
        accuracies.append(acc)
        print(f"Epoch {epoch+1}, Accuracy: {acc:.4f}")

    return accuracies

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
vocab_size = len(vocab)
embed_dim = 128
model_accuracies = {}

print("\nTraining RNN:")
rnn_acc = train(RNNModel(vocab_size, embed_dim), train_loader, val_loader)
model_accuracies['RNN'] = rnn_acc

print("\nTraining LSTM:")
lstm_acc = train(LSTMModel(vocab_size, embed_dim), train_loader, val_loader)
model_accuracies['LSTM'] = lstm_acc

print("\nTraining Transformer:")
trans_acc = train(TransformerModel(vocab_size, embed_dim), train_loader, val_loader)
model_accuracies['Transformer'] = trans_acc

